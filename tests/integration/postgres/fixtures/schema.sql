-- Producer test tables; same types/constraints as the inspected auth schema.
CREATE TABLE sessions (
 id uuid PRIMARY KEY,
 user_id integer NOT NULL REFERENCES auth(id) ON DELETE RESTRICT,
 status varchar(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','REVOKED')),
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 last_seen_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 expires_at timestamptz NOT NULL,
 revoked_at timestamptz,
 revoked_by integer REFERENCES auth(id) ON DELETE RESTRICT,
 revoke_reason varchar(500),
 device_label varchar(200),
 user_agent varchar(1000),
 ip_address inet,
 auth_version bigint CONSTRAINT sessions_auth_version_ck CHECK (auth_version IS NULL OR auth_version >= 1),
 CHECK (expires_at > created_at),
 CHECK ((status='ACTIVE' AND revoked_at IS NULL) OR
        (status='REVOKED' AND revoked_at IS NOT NULL AND revoke_reason IS NOT NULL AND char_length(btrim(revoke_reason)) BETWEEN 3 AND 500))
);
CREATE INDEX sessions_user_status_expiry_idx ON sessions(user_id,status,expires_at);
CREATE TABLE refresh_tokens (
 id uuid PRIMARY KEY,
 session_id uuid NOT NULL REFERENCES sessions(id) ON DELETE RESTRICT,
 token_hash bytea NOT NULL UNIQUE CHECK (octet_length(token_hash)>0),
 family_id uuid NOT NULL,
 issued_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 expires_at timestamptz NOT NULL CHECK (expires_at>issued_at),
 consumed_at timestamptz,
 revoked_at timestamptz,
 replaced_by uuid UNIQUE REFERENCES refresh_tokens(id) ON DELETE RESTRICT,
 CHECK (replaced_by IS NULL OR (replaced_by<>id AND consumed_at IS NOT NULL))
);
CREATE INDEX refresh_tokens_family_idx ON refresh_tokens(family_id);
CREATE INDEX refresh_tokens_session_idx ON refresh_tokens(session_id,expires_at);

