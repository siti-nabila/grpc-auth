CREATE TABLE auth (
 "id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
 "email" character varying(100) NOT NULL,
 "password" character varying(150) NOT NULL,
 "created_at" timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
 "updated_at" timestamp without time zone,
 "deleted_at" timestamp without time zone,
 "status" character varying(16) DEFAULT 'PENDING'::character varying NOT NULL,
 "auth_version" bigint DEFAULT 1 NOT NULL,
 "must_change_password" boolean DEFAULT false NOT NULL,
 "version" bigint DEFAULT 1 NOT NULL,
 "password_changed_at" timestamp with time zone,
 CONSTRAINT "PK_auth" PRIMARY KEY (id),
 CONSTRAINT "auth_email_normalized_ck" CHECK ((((email)::text = lower(btrim((email)::text))) AND ((email)::text <> ''::text))),
 CONSTRAINT "auth_status_ck" CHECK (((status)::text = ANY ((ARRAY['PENDING'::character varying, 'ACTIVE'::character varying, 'SUSPENDED'::character varying, 'DEACTIVATED'::character varying])::text[]))),
 CONSTRAINT "auth_version_ck" CHECK (((version >= 1) AND (auth_version >= 1))),
 CONSTRAINT "unique_key_email" UNIQUE (email)
);

CREATE TABLE profile (
 "id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
 "user_id" integer NOT NULL,
 "name" character varying(100),
 "address" character varying(250),
 "phone" character varying(20),
 CONSTRAINT "fk_user_id_id" FOREIGN KEY (user_id) REFERENCES auth(id) ON DELETE RESTRICT,
 CONSTRAINT "profile_pk" PRIMARY KEY (id),
 CONSTRAINT "profile_user_id_uq" UNIQUE (user_id)
);

CREATE TABLE role (
 "id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
 "role_name" character varying(50) NOT NULL,
 "role_code" integer DEFAULT nextval('role_numeric_code_seq'::regclass) NOT NULL,
 "role_description" character varying(100),
 "application_id" integer NOT NULL,
 "code" character varying(100) NOT NULL,
 "status" character varying(16) DEFAULT 'ACTIVE'::character varying NOT NULL,
 "is_system" boolean DEFAULT false NOT NULL,
 "version" bigint DEFAULT 1 NOT NULL,
 "created_at" timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
 "updated_at" timestamp with time zone,
 CONSTRAINT "role_application_fk" FOREIGN KEY (application_id) REFERENCES applications(id) ON DELETE RESTRICT,
 CONSTRAINT "role_code_string_ck" CHECK (((code)::text ~ '^[a-z][a-z0-9_]*[.][a-z][a-z0-9_]*$'::text)),
 CONSTRAINT "role_code_string_uq" UNIQUE (code),
 CONSTRAINT "role_status_ck" CHECK (((status)::text = ANY ((ARRAY['ACTIVE'::character varying, 'DISABLED'::character varying])::text[]))),
 CONSTRAINT "role_version_ck" CHECK ((version >= 1)),
 CONSTRAINT "uq_role_code" UNIQUE (role_code),
 CONSTRAINT "user_id_pkey" PRIMARY KEY (id)
);

CREATE TABLE user_role (
 "id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
 "user_id" integer NOT NULL,
 "role_id" integer NOT NULL,
 "status" character varying(16) DEFAULT 'ACTIVE'::character varying NOT NULL,
 "granted_by" integer,
 "granted_at" timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
 "revoked_by" integer,
 "revoked_at" timestamp with time zone,
 "revoke_reason" character varying(500),
 CONSTRAINT "PK_user_role" PRIMARY KEY (id),
 CONSTRAINT "role_fk" FOREIGN KEY (role_id) REFERENCES role(id),
 CONSTRAINT "user_fk" FOREIGN KEY (user_id) REFERENCES auth(id),
 CONSTRAINT "user_role_granted_by_fk" FOREIGN KEY (granted_by) REFERENCES auth(id) ON DELETE RESTRICT,
 CONSTRAINT "user_role_pair_uq" UNIQUE (user_id, role_id),
 CONSTRAINT "user_role_revocation_ck" CHECK (((((status)::text = 'ACTIVE'::text) AND (revoked_at IS NULL)) OR (((status)::text = 'REVOKED'::text) AND (revoked_at IS NOT NULL) AND (revoke_reason IS NOT NULL) AND ((char_length(btrim((revoke_reason)::text)) >= 3) AND (char_length(btrim((revoke_reason)::text)) <= 500))))),
 CONSTRAINT "user_role_revoked_by_fk" FOREIGN KEY (revoked_by) REFERENCES auth(id) ON DELETE RESTRICT,
 CONSTRAINT "user_role_status_ck" CHECK (((status)::text = ANY ((ARRAY['ACTIVE'::character varying, 'REVOKED'::character varying])::text[])))
);

