-- ROLE: numeric code dipertahankan; string code menjadi identifier IAM baru.
ALTER TABLE public.role
    ADD COLUMN application_id integer,
    ADD COLUMN code varchar(100),
    ADD COLUMN status varchar(16) NOT NULL DEFAULT 'ACTIVE',
    ADD COLUMN is_system boolean NOT NULL DEFAULT false,
    ADD COLUMN version bigint NOT NULL DEFAULT 1,
    ADD COLUMN created_at timestamptz,
    ADD COLUMN updated_at timestamptz;

UPDATE public.role
SET application_id = (SELECT id FROM public.applications WHERE code = 'iam'),
    code = CASE role_code
        WHEN 1 THEN 'iam.member'
        WHEN 2 THEN 'iam.platform_admin'
        ELSE 'iam.legacy_' || id::text
    END,
    is_system = true;
-- Legacy role lain tidak otomatis memperoleh permission baru.
-- created_at legacy dibiarkan NULL; tanggal historis tidak direkayasa.

ALTER TABLE public.role
    ALTER COLUMN application_id SET NOT NULL,
    ALTER COLUMN code SET NOT NULL,
    ALTER COLUMN created_at SET DEFAULT CURRENT_TIMESTAMP,
    ADD CONSTRAINT role_application_fk FOREIGN KEY (application_id)
        REFERENCES public.applications (id) ON DELETE RESTRICT,
    ADD CONSTRAINT role_code_string_uq UNIQUE (code),
    ADD CONSTRAINT role_status_ck CHECK (status IN ('ACTIVE', 'DISABLED')),
    ADD CONSTRAINT role_version_ck CHECK (version >= 1),
    ADD CONSTRAINT role_code_string_ck
        CHECK (code ~ '^[a-z][a-z0-9_]*[.][a-z][a-z0-9_]*$');

CREATE SEQUENCE public.role_numeric_code_seq AS integer MINVALUE 1;
SELECT setval('public.role_numeric_code_seq',
              greatest(coalesce(max(role_code), 0), 0)::bigint + 1, false)
FROM public.role;
ALTER SEQUENCE public.role_numeric_code_seq OWNED BY public.role.role_code;
ALTER TABLE public.role ALTER COLUMN role_code
    SET DEFAULT nextval('public.role_numeric_code_seq');
-- uq_role_code dan PK sudah mempunyai index B-tree, dengan backward scan.
DROP INDEX public.idx_role_code;
DROP INDEX public.idx_role_id;
CREATE INDEX role_application_status_id_idx ON public.role (application_id, status, id);

-- USER_ROLE: gunakan assignment existing, tanpa insert assignment baru.
ALTER TABLE public.user_role
    ADD COLUMN status varchar(16) NOT NULL DEFAULT 'ACTIVE',
    ADD COLUMN granted_by integer,
    ADD COLUMN granted_at timestamptz,
    ADD COLUMN revoked_by integer,
    ADD COLUMN revoked_at timestamptz,
    ADD COLUMN revoke_reason varchar(500),
    ADD CONSTRAINT user_role_pair_uq UNIQUE (user_id, role_id),
    ADD CONSTRAINT user_role_status_ck CHECK (status IN ('ACTIVE', 'REVOKED')),
    ADD CONSTRAINT user_role_granted_by_fk FOREIGN KEY (granted_by)
        REFERENCES public.auth (id) ON DELETE RESTRICT,
    ADD CONSTRAINT user_role_revoked_by_fk FOREIGN KEY (revoked_by)
        REFERENCES public.auth (id) ON DELETE RESTRICT,
    ADD CONSTRAINT user_role_revocation_ck CHECK (
        (status = 'ACTIVE' AND revoked_at IS NULL)
        OR (status = 'REVOKED' AND revoked_at IS NOT NULL
            AND revoke_reason IS NOT NULL
            AND char_length(btrim(revoke_reason)) BETWEEN 3 AND 500)
    );
ALTER TABLE public.user_role ALTER COLUMN granted_at SET DEFAULT CURRENT_TIMESTAMP;
COMMENT ON COLUMN public.user_role.granted_at IS
    'NULL untuk assignment legacy yang waktu grant aslinya tidak diketahui';
CREATE INDEX user_role_user_status_idx ON public.user_role (user_id, status, role_id);
CREATE INDEX user_role_role_status_idx ON public.user_role (role_id, status, user_id);

-- SEARCH: pertahankan data/unique profile. Ubah jenis index, bukan duplikasi.
CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;
-- Jika extension existing berada di schema lain, gunakan operator class
-- schema tersebut; jangan memindahkan extension secara otomatis.
ALTER TABLE public.user_profile_search
    DROP CONSTRAINT profile_fk,
    ADD CONSTRAINT profile_fk FOREIGN KEY (profile_id)
        REFERENCES public.profile (id) ON DELETE CASCADE ON UPDATE CASCADE;
DROP INDEX public.idx_user_profile_search_fts_keyword;
DROP INDEX public.idx_user_profile_search_fts_lexeme_text_trgm;
CREATE INDEX idx_user_profile_search_fts_keyword
    ON public.user_profile_search USING gin (fts_keyword);
CREATE INDEX idx_user_profile_search_fts_lexeme_text_trgm
    ON public.user_profile_search USING gin (fts_lexeme_text public.gin_trgm_ops);

-- PERMISSIONS: catalog code penuh; equality application/prefix dicek service/seed.
CREATE TABLE public.permissions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id integer NOT NULL REFERENCES public.applications (id) ON DELETE RESTRICT,
    code varchar(150) NOT NULL UNIQUE,
    description text NOT NULL,
    CONSTRAINT permissions_code_ck CHECK (
        code ~ '^[a-z][a-z0-9_]*([.][a-z][a-z0-9_]*){2,}$'
    )
);
CREATE INDEX permissions_application_idx ON public.permissions (application_id, id);

CREATE TABLE public.role_permissions (
    role_id integer NOT NULL REFERENCES public.role (id) ON DELETE RESTRICT,
    permission_id integer NOT NULL REFERENCES public.permissions (id) ON DELETE RESTRICT,
    PRIMARY KEY (role_id, permission_id)
);
CREATE INDEX role_permissions_permission_idx ON public.role_permissions (permission_id, role_id);

CREATE TABLE public.user_application_access (
    user_id integer NOT NULL REFERENCES public.auth (id) ON DELETE RESTRICT,
    application_id integer NOT NULL REFERENCES public.applications (id) ON DELETE RESTRICT,
    status varchar(16) NOT NULL DEFAULT 'ACTIVE',
    granted_by integer REFERENCES public.auth (id) ON DELETE RESTRICT,
    granted_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_by integer REFERENCES public.auth (id) ON DELETE RESTRICT,
    revoked_at timestamptz,
    revoke_reason varchar(500),
    PRIMARY KEY (user_id, application_id),
    CONSTRAINT application_access_status_ck CHECK (status IN ('ACTIVE', 'REVOKED')),
    CONSTRAINT application_access_revocation_ck CHECK (
        (status = 'ACTIVE' AND revoked_at IS NULL)
        OR (status = 'REVOKED' AND revoked_at IS NOT NULL
            AND revoke_reason IS NOT NULL
            AND char_length(btrim(revoke_reason)) BETWEEN 3 AND 500)
    )
);
CREATE INDEX application_access_application_status_idx
    ON public.user_application_access (application_id, status, user_id);

-- UUID session/token/event dihasilkan aplikasi, tanpa seed token/password.
CREATE TABLE public.sessions (
    id uuid PRIMARY KEY,
    user_id integer NOT NULL REFERENCES public.auth (id) ON DELETE RESTRICT,
    status varchar(16) NOT NULL DEFAULT 'ACTIVE',
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    revoked_by integer REFERENCES public.auth (id) ON DELETE RESTRICT,
    revoke_reason varchar(500),
    device_label varchar(200),
    user_agent varchar(1000),
    ip_address inet,
    CONSTRAINT sessions_status_ck CHECK (status IN ('ACTIVE', 'REVOKED')),
    CONSTRAINT sessions_expiry_ck CHECK (expires_at > created_at),
    CONSTRAINT sessions_revocation_ck CHECK (
        (status = 'ACTIVE' AND revoked_at IS NULL)
        OR (status = 'REVOKED' AND revoked_at IS NOT NULL
            AND revoke_reason IS NOT NULL
            AND char_length(btrim(revoke_reason)) BETWEEN 3 AND 500)
    )
);
CREATE INDEX sessions_user_status_expiry_idx ON public.sessions (user_id, status, expires_at);

CREATE TABLE public.refresh_tokens (
    id uuid PRIMARY KEY,
    session_id uuid NOT NULL REFERENCES public.sessions (id) ON DELETE RESTRICT,
    token_hash bytea NOT NULL UNIQUE,
    family_id uuid NOT NULL,
    issued_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at timestamptz NOT NULL,
    consumed_at timestamptz,
    revoked_at timestamptz,
    replaced_by uuid UNIQUE REFERENCES public.refresh_tokens (id) ON DELETE RESTRICT,
    CONSTRAINT refresh_tokens_expiry_ck CHECK (expires_at > issued_at),
    CONSTRAINT refresh_tokens_replacement_ck CHECK (
        replaced_by IS NULL OR (replaced_by <> id AND consumed_at IS NOT NULL)
    ),
    CONSTRAINT refresh_tokens_hash_ck CHECK (octet_length(token_hash) > 0)
);
CREATE INDEX refresh_tokens_session_idx ON public.refresh_tokens (session_id, expires_at);
CREATE INDEX refresh_tokens_family_idx ON public.refresh_tokens (family_id);

CREATE TABLE public.audit_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id integer REFERENCES public.auth (id) ON DELETE RESTRICT,
    actor_service varchar(100),
    action varchar(100) NOT NULL,
    target_type varchar(50) NOT NULL,
    target_id varchar(100) NOT NULL,
    safe_before jsonb,
    safe_after jsonb,
    reason varchar(500),
    request_id varchar(100),
    trace_id varchar(100),
    occurred_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT audit_actor_ck CHECK (
        actor_user_id IS NOT NULL OR nullif(btrim(actor_service), '') IS NOT NULL
    )
);
CREATE INDEX audit_target_time_idx ON public.audit_logs (target_type, target_id, occurred_at DESC, id DESC);
CREATE INDEX audit_actor_time_idx ON public.audit_logs (actor_user_id, occurred_at DESC, id DESC);
CREATE INDEX audit_time_idx ON public.audit_logs (occurred_at DESC, id DESC);

CREATE TABLE public.outbox_events (
    event_id uuid PRIMARY KEY,
    event_type varchar(100) NOT NULL,
    schema_version integer NOT NULL DEFAULT 1,
    aggregate_type varchar(50) NOT NULL,
    aggregate_id varchar(100) NOT NULL,
    aggregate_version bigint NOT NULL,
    payload jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at timestamptz,
    attempts integer NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lease_owner varchar(100),
    lease_expires_at timestamptz,
    last_error_code varchar(100),
    CONSTRAINT outbox_version_ck CHECK (aggregate_version >= 1 AND schema_version >= 1),
    CONSTRAINT outbox_attempts_ck CHECK (attempts >= 0),
    CONSTRAINT outbox_lease_ck CHECK ((lease_owner IS NULL) = (lease_expires_at IS NULL))
);
CREATE INDEX outbox_pending_idx ON public.outbox_events (next_attempt_at, created_at, event_id)
    WHERE published_at IS NULL;

CREATE TABLE public.idempotency_records (
    actor_id integer NOT NULL REFERENCES public.auth (id) ON DELETE RESTRICT,
    method varchar(100) NOT NULL,
    route_scope varchar(300) NOT NULL,
    key varchar(200) NOT NULL,
    request_hash bytea NOT NULL,
    safe_response jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at timestamptz NOT NULL,
    PRIMARY KEY (actor_id, method, route_scope, key),
    CONSTRAINT idempotency_key_ck CHECK (btrim(key) <> ''),
    CONSTRAINT idempotency_expiry_ck CHECK (expires_at > created_at),
    CONSTRAINT idempotency_hash_ck CHECK (octet_length(request_hash) > 0)
);
CREATE INDEX idempotency_expiry_idx ON public.idempotency_records (expires_at);

