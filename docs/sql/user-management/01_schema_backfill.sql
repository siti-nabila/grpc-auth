-- PostgreSQL 16+. Migration satu kali, berdasarkan DDL existing yang diberikan.
-- Tidak menghapus user, profile, role, assignment, atau password existing.
-- Jalankan dengan stop-on-error; seluruh perubahan berada dalam satu transaksi.
-- Jadwalkan saat write aplikasi dihentikan: ALTER TABLE/backfill memegang lock.
BEGIN;
SET LOCAL TIME ZONE 'Asia/Jakarta';
SET LOCAL lock_timeout = '10s';
SET LOCAL statement_timeout = '5min';
SELECT pg_advisory_xact_lock(7301, 1);
LOCK TABLE public.auth, public.profile, public.role, public.user_role,
           public.user_profile_search IN ACCESS EXCLUSIVE MODE;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM public.auth
               WHERE email IS NULL OR btrim(email) = ''
                  OR email <> lower(btrim(email))) THEN
        RAISE EXCEPTION 'Email null/kosong/belum normalized; perbaiki data sebelum migration';
    END IF;
    IF EXISTS (SELECT 1 FROM public.auth
               WHERE password IS NULL OR btrim(password) = '') THEN
        RAISE EXCEPTION 'Password hash kosong; perbaiki melalui auth service';
    END IF;
    IF EXISTS (SELECT 1 FROM public.auth GROUP BY email HAVING count(*) > 1) THEN
        RAISE EXCEPTION 'Duplicate email; migration tidak menghapus data';
    END IF;
    IF EXISTS (SELECT 1 FROM public.profile GROUP BY user_id HAVING count(*) > 1) THEN
        RAISE EXCEPTION 'Duplicate profile.user_id; tentukan resolusi data dahulu';
    END IF;
    IF EXISTS (SELECT 1 FROM public.user_role
               GROUP BY user_id, role_id HAVING count(*) > 1) THEN
        RAISE EXCEPTION 'Duplicate user_role; tentukan resolusi data dahulu';
    END IF;
    IF EXISTS (SELECT 1 FROM public.profile p
               WHERE NOT EXISTS (SELECT 1 FROM public.auth a WHERE a.id = p.user_id))
       OR EXISTS (SELECT 1 FROM public.user_role ur
                  WHERE NOT EXISTS (SELECT 1 FROM public.auth a WHERE a.id = ur.user_id)
                     OR NOT EXISTS (SELECT 1 FROM public.role r WHERE r.id = ur.role_id))
       OR EXISTS (SELECT 1 FROM public.user_profile_search s
                  WHERE NOT EXISTS (SELECT 1 FROM public.profile p WHERE p.id = s.profile_id)) THEN
        RAISE EXCEPTION 'Orphan foreign key; perbaiki data sebelum migration';
    END IF;
    IF EXISTS (SELECT 1 FROM public.role WHERE role_code = 2147483647) THEN
        RAISE EXCEPTION 'role_code integer exhausted; perlu keputusan tipe ID/code';
    END IF;
END $$;

-- AUTH: password tetap hash existing; TEXT menghindari batas format hash baru.
ALTER TABLE public.auth
    ALTER COLUMN email SET NOT NULL,
    ALTER COLUMN password TYPE text,
    ALTER COLUMN password SET NOT NULL,
    ADD COLUMN status varchar(16),
    ADD COLUMN auth_version bigint NOT NULL DEFAULT 1,
    ADD COLUMN must_change_password boolean NOT NULL DEFAULT false,
    ADD COLUMN version bigint NOT NULL DEFAULT 1,
    ADD COLUMN password_changed_at timestamptz;

UPDATE public.auth
SET status = CASE WHEN deleted_at IS NULL THEN 'ACTIVE' ELSE 'DEACTIVATED' END;

ALTER TABLE public.auth
    ALTER COLUMN status SET NOT NULL,
    ALTER COLUMN status SET DEFAULT 'PENDING',
    ADD CONSTRAINT auth_status_ck
        CHECK (status IN ('PENDING', 'ACTIVE', 'SUSPENDED', 'DEACTIVATED')),
    ADD CONSTRAINT auth_version_ck CHECK (version >= 1 AND auth_version >= 1),
    ADD CONSTRAINT auth_email_normalized_ck
        CHECK (email = lower(btrim(email)) AND email <> '');

COMMENT ON COLUMN public.auth.password_changed_at IS
    'NULL untuk password existing yang waktu perubahan terakhirnya tidak diketahui';
-- Pertahankan PK_auth, unique_key_email, dan idx_id_email.
CREATE INDEX auth_status_id_idx ON public.auth (status, id);

-- PROFILE: satu profil per user. SET NULL bertentangan dengan NOT NULL.
ALTER TABLE public.profile
    DROP CONSTRAINT fk_user_id_id,
    ADD CONSTRAINT fk_user_id_id FOREIGN KEY (user_id)
        REFERENCES public.auth (id) ON DELETE RESTRICT ON UPDATE NO ACTION,
    ADD CONSTRAINT profile_user_id_uq UNIQUE (user_id);
-- UNIQUE baru mencakup lookup user_id dan scan kedua arah.
DROP INDEX public.idx_user_id;

-- APPLICATIONS: catalog; ID user/role existing tetap INTEGER.
CREATE TABLE public.applications (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(50) NOT NULL UNIQUE,
    name varchar(100) NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'ACTIVE',
    is_system boolean NOT NULL DEFAULT false,
    CONSTRAINT applications_code_ck CHECK (code ~ '^[a-z][a-z0-9_]*$'),
    CONSTRAINT applications_status_ck CHECK (status IN ('ACTIVE', 'DISABLED'))
);

INSERT INTO public.applications (code, name, is_system)
